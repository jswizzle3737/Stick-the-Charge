"""Refresh the existing selected entries from the Justice Laws section pages.

This does not discover or certify every federal offence. Pages that cannot be
reproduced by the conservative extractor remain explicitly unavailable.
"""
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import date
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import time
import urllib.request
from urllib.parse import urlparse

from tools.legislation import ExtractionError, extract_section

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://laws-lois.justice.gc.ca"
SELECTED = ROOT / "src" / "charges.rs"
OUTPUT = ROOT / "src" / "legislation_data.rs"
EXTRA = {("C-46", section) for section in ("47", "48", "52.3", "59", "60", "63", "64", "67", "73", "79", "82.1", "83.01", "131", "234", "235", "265", "334", "343", "355", "367", "734", "737", "787", "320.19")}
EXTRA |= {("C-38.8", section) for section in ("2", "4.1")}
EXTRA |= {("C-46", section) for section in ("83.032", "83.08", "83.1", "83.11")}
EXTRA |= {("C-46", section) for section in ("84",)}
EXTRA |= {("C-46", section) for section in ("130.1", "133")}
EXTRA |= {("C-46", section) for section in ("320.2", "320.21")}
PATTERN = re.compile(r'c\("([^"]+)", "[^"]+", (\w+), \w+, "[^"]+", "[^"]+"\)')


def targets_from_source(source):
    matches = PATTERN.findall(source)
    if len(matches) < 40:
        raise ValueError(f"Only found {len(matches)} selected charges; refusing to refresh")
    return {("C-38.8" if category == "Drugs" else "C-46", number.split("(")[0]) for number, category in matches} | EXTRA


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "StickTheCharge/0.1 (legislation source refresh)"})
    last_error = None
    for attempt in range(2):
        try:
            with urllib.request.urlopen(request, timeout=25) as response:
                actual = urlparse(response.geturl())
                expected = urlparse(url)
                if actual.scheme != "https" or actual.hostname != expected.hostname or actual.path != expected.path:
                    raise ValueError("unexpected source redirect")
                raw = response.read(4_000_001)
                if len(raw) > 4_000_000:
                    raise ValueError("source page is too large")
                return raw
        except Exception as error:
            last_error = error
            if attempt == 0:
                time.sleep(0.5)
    raise RuntimeError(f"source request failed: {last_error}")


def current_to_from_home(html):
    match = re.search(r"current to\s*\ufeff?(\d{4}-\d{2}-\d{2})", html, re.IGNORECASE)
    if not match:
        raise ExtractionError("Justice Laws home page has no current-to date")
    return date.fromisoformat(match.group(1)).isoformat()


def acquire(target, minimum_date):
    act, section = target
    url = f"{ORIGIN}/eng/acts/{act}/section-{section}.html"
    raw = fetch(url)
    extracted = extract_section(raw.decode("utf-8-sig"), section, minimum_date)
    return ({"act": act, "section": section, "current_to": extracted.current_to,
             "text": extracted.text, "source_sha256": hashlib.sha256(raw).hexdigest()}, raw)


def rust_string(value):
    if any(ord(char) < 32 and char not in "\n\t" for char in value):
        raise ValueError("unsupported control character in source text")
    return json.dumps(value, ensure_ascii=False)


def render_rust(records):
    lines = ["// Generated by tools/refresh_selected.py from Justice Laws section pages.",
             "// Unofficial reproduction; preserve source wording and current-to metadata.",
             "pub static SELECTED_LEGISLATION: &[Legislation] = &["]
    for record in sorted(records, key=lambda item: (item["act"], item["section"])):
        values = ", ".join(f'{key}: {rust_string(record[key])}' for key in ("act", "section", "current_to", "text", "source_sha256"))
        lines.append(f"    Legislation {{ {values} }},")
    lines.append("];\n")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audit-dir", type=Path, help="optional directory for downloaded source pages used in independent verification")
    args = parser.parse_args()
    if args.audit_dir:
        args.audit_dir.mkdir(parents=True, exist_ok=True)
    targets = targets_from_source(SELECTED.read_text(encoding="utf-8"))
    minimum_date = current_to_from_home(fetch(f"{ORIGIN}/eng/").decode("utf-8-sig"))
    print(f"Justice Laws home page current to {minimum_date}; checking {len(targets)} selected sections.", flush=True)
    records, failures = [], []
    with ThreadPoolExecutor(max_workers=2) as executor:
        futures = {executor.submit(acquire, target, minimum_date): target for target in sorted(targets)}
        for future in as_completed(futures):
            target = futures[future]
            try:
                record, raw = future.result()
                if args.audit_dir:
                    (args.audit_dir / f'{record["act"]}_{record["section"]}.html').write_bytes(raw)
                records.append(record)
            except Exception as error:
                failures.append((target, str(error)))
            if (len(records) + len(failures)) % 10 == 0:
                print(f"Checked {len(records) + len(failures)}/{len(targets)} sections.", flush=True)
    if not records:
        raise RuntimeError("No sections passed extraction; existing data was not replaced")
    output = render_rust(records)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=OUTPUT.parent, delete=False) as handle:
        temp_name = handle.name
        handle.write(output)
    os.replace(temp_name, OUTPUT)
    print(f"Stored {len(records)} of {len(targets)} sections. Missing sections remain unavailable.")
    for (act, section), error in sorted(failures):
        print(f"NOT INCLUDED {act} {section}: {error}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
